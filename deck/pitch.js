const CHERRY = 'A4161A', INK = '15192E', MUTE = '5B6178', PAPER = 'FFFFFF';
const GOOD = '1B7F4B', WARN = 'C77700', SOFT = 'F4F6FB', HAIR = 'DDE3F0';
const F = 'Tahoma';
const W = 13.3, H = 7.5, M = 0.62;

const rtl = (o = {}) => ({ fontFace: F, rtlMode: true, align: 'right', margin: 0, ...o });
const img = n => path.join(__dirname, 'img', n);
/* برچسبی که با عدد شروع شود در بازنمایی دوجهته عدد را به انتها پرت می‌کند.
   RLM ابتدای رشته، جهت پاراگراف را قفل می‌کند. */
const R = t => '\u200F' + t;
const FA = '۰۱۲۳۴۵۶۷۸۹';
const fa = n => String(n).replace(/[0-9]/g, d => FA[+d]);
/* توکن لاتین وسط جملهٔ فارسی، جهت پاراگراف را به چپ‌به‌راست می‌برد و کل
   سطر را جابه‌جا می‌کند. RLM دو طرفش، توکن را جزیره می‌کند. */
const iso = t => String(t).replace(/([A-Za-z][A-Za-z0-9._+-]*)/g, '\u200F$1\u200F');

function slide(bg) {
  const s = P.addSlide();
  s.background = { color: bg || PAPER };
  return s;
}

function title(s, txt, sub, dark) {
  s.addText(txt, rtl({ x: M, y: 0.40, w: W - 2 * M, h: 0.84, fontSize: 31, bold: true,
    color: dark ? WHITE : INK, valign: 'middle' }));
  if (sub) s.addText(sub, rtl({ x: M, y: 1.22, w: W - 2 * M, h: 0.46, fontSize: 14,
    color: dark ? ICE : MUTE, valign: 'top' }));
}

function card(s, x, y, w, h, fill, line) {
  s.addShape(P.ShapeType.roundRect, { x, y, w, h, rectRadius: 0.10,
    fill: { color: fill || SOFT }, line: { color: line || fill || HAIR, width: 1 } });
}

function stat(s, x, y, w, big, lab, color, note) {
  s.addText(big, rtl({ x, y, w, h: 0.76, fontSize: 33, bold: true, color,
    align: 'center', valign: 'middle' }));
  s.addText(lab, rtl({ x, y: y + 0.76, w, h: 0.38, fontSize: 12.5, color: INK,
    align: 'center' }));
  if (note) s.addText(note, rtl({ x, y: y + 1.12, w, h: 0.66, fontSize: 10.5,
    color: MUTE, align: 'center', valign: 'top' }));
}

/* گلولهٔ خودکار در راست‌به‌چپ سمت اشتباه می‌افتد؛ خودمان می‌گذاریم. */
function bullets(s, x, y, w, items, size = 13.5, color = INK) {
  s.addText(items.map((t, i) => ({ text: '\u200F\u2022\u00A0\u200F' + t,
    options: { breakLine: i < items.length - 1 } })),
    rtl({ x, y, w, h: 0.42 * items.length + 0.45, fontSize: size, color,
      paraSpaceAfter: 8, lineSpacingMultiple: 1.16, valign: 'top' }));
}

/* جدول‌ها در pptxgenjs راست‌به‌چپ نمی‌شوند؛ ستون‌ها را معکوس می‌کنیم. */
function table(s, rows, { x, y, w, colW, rowH = 0.44, size = 12.5, hi = -1 }) {
  s.addTable(rows.map((r, ri) => [...r].reverse().map(c => ({
    text: String(c),
    options: { fontFace: F, rtlMode: true, align: 'right',
      fontSize: ri === 0 ? size - 1.5 : size,
      bold: ri === 0 || ri === hi,
      color: ri === 0 ? WHITE : (ri === hi ? GOOD : INK),
      fill: { color: ri === 0 ? NAVY : (ri === hi ? 'EAF6EF' : (ri % 2 ? SOFT : PAPER)) },
      margin: 8 },
  }))), { x, y, w, colW: [...colW].reverse(), rowH });
}

function shot(s, file, { x, y, w, h }) {
  s.addImage({ path: img(file), x, y, w, h,
    rounding: false, shadow: { type: 'outer', angle: 90, blur: 9, offset: 2,
      color: '9AA3BC', opacity: 0.35 } });
}

function footNote(s, txt) {
  s.addText(txt, rtl({ x: M, y: H - 0.86, w: W - 2 * M, h: 0.34, fontSize: 10.5,
    color: MUTE }));
}

